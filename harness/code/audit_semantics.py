"""Audit the *rendered* Atlas for repetitive node meaning, not just AST IDs.

Run after export.py.  This is intentionally a detector, never an automatic
rewriter: different Python symbols may implement different behaviors even when
their autogenerated Atlas cards look identical.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
ATLAS_PREFIX = "window.OPENRESEARCH_ATLAS = "
HIERARCHY_EDGES = frozenset({"contains", "decomposes"})
# Action swapping does not distinguish a scientific responsibility.
ACTIONS = (
    "实现", "管理", "负责", "执行", "处理", "组织", "提供", "构建",
    "运行", "完成", "维护", "支持", "配置", "启动", "读取", "获取",
    "验证", "校验", "检查", "分析", "评估", "汇总", "生成", "计算",
    "建立", "调用", "加载", "记录", "保存", "更新", "创建", "删除",
    "绑定", "适配", "注册", "准备", "转发", "连接", "测量", "监控",
    "封装", "统一",
)
BOILERPLATE = (
    "源码依据和调用参数可在节点的展开说明中查看",
    "源码依据和调用参数在展开说明中查看",
    "sourcebackeddetail",
)
BOILERPLATE_RE = re.compile(
    r"(?:[；;，,。]\s*)?源码依据和调用参数可在节点的展开说明中查看[。.]?",
    flags=re.UNICODE,
)


def normalize(text: str) -> str:
    value = unicodedata.normalize("NFKC", str(text or "")).casefold()
    return re.sub(r"[\W_]+", "", value, flags=re.UNICODE)


def purpose(text: str) -> str:
    """Remove boilerplate and action prefixes, never source identifiers."""
    value = BOILERPLATE_RE.sub("", str(text or ""))
    value = normalize(value)
    for phrase in BOILERPLATE:
        value = value.replace(normalize(phrase), "")
    # Only beginning verbs: preserve the actual research object and qualifiers.
    for _ in range(3):
        found = next((action for action in ACTIONS if value.startswith(action)), None)
        if not found:
            break
        value = value[len(found):]
    return value


def similarity(left: str, right: str) -> float:
    """Character bigram Jaccard works for Chinese without word segmentation."""
    if len(left) < 8 or len(right) < 8:
        return 0.0
    a = {left[i : i + 2] for i in range(len(left) - 1)}
    b = {right[i : i + 2] for i in range(len(right) - 1)}
    return len(a & b) / len(a | b) if a and b else 0.0


def _node_record(node: dict) -> dict:
    return {
        "id": node["id"],
        "kind": node.get("kind") or node.get("type") or "",
        "title": node.get("title", ""),
        "summary": node.get("summary", ""),
        "description": node.get("description", ""),
        "source_path": node.get("path") or node.get("source_path") or "",
        "source_symbol": node.get("source_symbol") or node.get("key_function") or "",
    }


def _group(view: str, parent: str, ids: list[str], nodes: dict, reason: str) -> dict:
    return {
        "tree": view,
        "parent": parent,
        "parent_title": nodes.get(parent, {}).get("title", ""),
        "reason": reason,
        "size": len(ids),
        "distinct_source_symbols": len({
            (nodes[x].get("path") or nodes[x].get("source_path") or "",
             nodes[x].get("source_symbol") or nodes[x].get("key_function") or "")
            for x in ids
        }),
        "members": [_node_record(nodes[x]) for x in ids],
    }


def _components(ids: list[str], linked: list[tuple[str, str]]) -> list[list[str]]:
    """Connected groups make large duplicate families visible without O(n²) output."""
    owners = {x: x for x in ids}

    def root(x: str) -> str:
        while owners[x] != x:
            owners[x] = owners[owners[x]]
            x = owners[x]
        return x

    for left, right in linked:
        a, b = root(left), root(right)
        if a != b:
            owners[b] = a
    groups = defaultdict(list)
    for item in ids:
        groups[root(item)].append(item)
    return [group for group in groups.values() if len(group) > 1]


def audit(graphs: dict) -> dict:
    """Audit every generated Tree; preserve all member IDs for manual repair."""
    issues = defaultdict(list)
    tree_counts = {}
    template_by_kind = Counter()
    repeated_members_by_kind = Counter()
    global_summaries = Counter()
    global_examples = {}

    for view, graph in graphs.items():
        if not isinstance(graph, dict) or not isinstance(graph.get("nodes"), list):
            continue
        nodes = {node["id"]: node for node in graph["nodes"]}
        tree_counts[view] = len(nodes)
        children = defaultdict(list)
        for edge in graph.get("edges") or []:
            if edge.get("type") in HIERARCHY_EDGES:
                parent, child = edge.get("source"), edge.get("target")
                if parent in nodes and child in nodes:
                    children[parent].append(child)
        for child, parent in (graph.get("parents") or {}).items():
            if child in nodes and parent in nodes:
                children[parent].append(child)

        for node in nodes.values():
            label, summary, description = (
                str(node.get(field) or "") for field in ("title", "summary", "description")
            )
            ident = node["id"]
            if normalize(summary):
                key = (view, normalize(summary))
                global_summaries[key] += 1
                global_examples[key] = summary
            if "源码依据和调用参数" in summary or any(
                normalize(phrase) in normalize(summary) for phrase in BOILERPLATE
            ):
                issues["template_summary"].append(_node_record(node) | {"tree": view})
                template_by_kind[node.get("kind") or node.get("type") or "?"] += 1
            if label and summary and purpose(label) and purpose(label) == purpose(summary):
                issues["tautological_purpose"].append(_node_record(node) | {"tree": view})
            detail = str(node.get("reader_explanation") or "")
            if summary and detail and (
                normalize(summary) == normalize(detail)
                or normalize(summary) in normalize(detail)
            ):
                issues["duplicated_explanation"].append(_node_record(node) | {"tree": view})
            if description and summary and normalize(description) == normalize(summary):
                issues["duplicated_description"].append(_node_record(node) | {"tree": view})

        if view == "code":
            # A semantic role duplicated under DIFFERENT parents was invisible
            # to the original sibling-only audit. Treat the entire Code Tree
            # as one responsibility inventory, while keeping full provenance.
            owner_of = {
                child: parent for parent, members in children.items()
                for child in members
            }
            for field in ("title", "summary"):
                global_groups = defaultdict(list)
                for node in nodes.values():
                    value = normalize(node.get(field))
                    if value:
                        global_groups[value].append(node["id"])
                for members in global_groups.values():
                    if len(members) < 2:
                        continue
                    issues["repeated_global_" + field].append({
                        "tree": view,
                        "parent": "<all Code branches>",
                        "reason": "exact normalized " + field + " across Code parents",
                        "size": len(members),
                        "members": [
                            _node_record(nodes[item]) | {"parent_id": owner_of.get(item, "")}
                            for item in members
                        ],
                    })

            all_ids = list(nodes)
            semantic_pairs = []
            for index, left in enumerate(all_ids):
                x = nodes[left]
                x_title, x_summary = purpose(x.get("title")), purpose(x.get("summary"))
                if len(x_title) < 8 or len(x_summary) < 8:
                    continue
                for right in all_ids[index + 1:]:
                    y = nodes[right]
                    if owner_of.get(left) == owner_of.get(right):
                        continue  # sibling similarity has its own report
                    y_title, y_summary = purpose(y.get("title")), purpose(y.get("summary"))
                    if len(y_title) < 8 or len(y_summary) < 8:
                        continue
                    if x_title == y_title and x_summary == y_summary:
                        semantic_pairs.append((left, right))
            for members in _components(all_ids, semantic_pairs):
                issues["similar_global_purpose"].append({
                    "tree": view,
                    "parent": "<all Code branches>",
                    "reason": "same title and summary purpose after action verb normalization",
                    "size": len(members),
                    "members": [
                        _node_record(nodes[item]) | {"parent_id": owner_of.get(item, "")}
                        for item in members
                    ],
                })

        for parent, candidate_ids in children.items():
            ids = list(dict.fromkeys(candidate_ids))
            if len(ids) < 1:
                continue
            grouped = {field: defaultdict(list) for field in ("title", "summary")}
            for ident in ids:
                node = nodes[ident]
                for field in grouped:
                    normalized = normalize(node.get(field))
                    if normalized:
                        grouped[field][normalized].append(ident)
                parent_node = nodes[parent]
                if normalize(node.get("title")) and purpose(node.get("title")) == purpose(parent_node.get("title")):
                    issues["duplicate_parent_title"].append(
                        _group(view, parent, [ident], nodes, "same parent/child purpose")
                    )
                if normalize(node.get("summary")) and purpose(node.get("summary")) == purpose(parent_node.get("summary")):
                    issues["duplicate_parent_purpose"].append(
                        _group(view, parent, [ident], nodes, "same parent/child summary")
                    )
            for field, values in grouped.items():
                for members in values.values():
                    if len(members) < 2:
                        continue
                    issues["repeated_sibling_" + field].append(
                        _group(view, parent, members, nodes, "exact normalized " + field)
                    )
                    if field == "title":
                        for ident in members:
                            repeated_members_by_kind[
                                nodes[ident].get("kind") or nodes[ident].get("type") or "?"
                            ] += 1

            near_pairs = []
            for i, left in enumerate(ids):
                for right in ids[i + 1:]:
                    x, y = nodes[left], nodes[right]
                    x_title, y_title = purpose(x.get("title")), purpose(y.get("title"))
                    x_sum, y_sum = purpose(x.get("summary")), purpose(y.get("summary"))
                    if (
                        (len(x_title) >= 6 and x_title == y_title)
                        or (len(x_sum) >= 8 and x_sum == y_sum)
                        or similarity(x_title, y_title) >= 0.82
                        or similarity(x_sum, y_sum) >= 0.85
                    ):
                        near_pairs.append((left, right))
            for members in _components(ids, near_pairs):
                issues["similar_sibling_purpose"].append(
                    _group(view, parent, members, nodes, "same object or >=0.82 title / >=0.85 summary bigram overlap")
                )

    counts = {key: len(records) for key, records in sorted(issues.items())}
    return {
        "tree_nodes": tree_counts,
        "code_nodes": tree_counts.get("code", 0),
        "counts": counts,
        "affected_nodes": {
            key: len({
                member["id"]
                for record in records
                for member in (record.get("members") or [record])
            }) for key, records in issues.items()
        },
        "template_by_kind": dict(template_by_kind),
        "repeated_members_by_kind": dict(repeated_members_by_kind),
        "top_repeated_summaries": [
            {"tree": key[0], "count": count, "example": global_examples[key]}
            for key, count in global_summaries.most_common(30) if count > 2
        ],
        "sample": {key: records[:5] for key, records in issues.items()},
        "issues": dict(issues),
    }


def load_atlas(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if ATLAS_PREFIX not in text:
        raise ValueError("Missing source-generated Atlas in " + str(path))
    return json.loads(text.partition(ATLAS_PREFIX)[2].strip().removesuffix(";"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "harness/visualization/data.js")
    parser.add_argument("--output", type=Path, help="Full JSON with every implicated node and parent")
    parser.add_argument("--check", action="store_true", help="Fail when repeated semantics remain")
    args = parser.parse_args()
    report = audit(load_atlas(args.input))
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    compact = {key: value for key, value in report.items() if key not in ("issues", "sample")}
    compact["sample"] = {
        key: [{"tree": item.get("tree"), "parent": item.get("parent"),
               "members": [member["id"] for member in item.get("members", [])]}
              for item in records[:3]] if key.startswith(("similar_sibling_", "repeated_sibling_"))
        else [item.get("id") or item.get("parent") for item in records[:3]]
        for key, records in report["sample"].items()
    }
    print("ATLAS_SEMANTIC_AUDIT=" + json.dumps(compact, ensure_ascii=False))
    blockers = (
        "repeated_sibling_title", "repeated_sibling_summary",
        "similar_sibling_purpose", "repeated_global_title",
        "repeated_global_summary", "similar_global_purpose",
        "template_summary", "tautological_purpose",
    )
    if args.check and any(report["counts"].get(key, 0) for key in blockers):
        raise SystemExit("Atlas semantic collisions remain; inspect --output report")


if __name__ == "__main__":
    main()
